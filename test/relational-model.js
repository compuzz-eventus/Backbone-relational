	it('change events in relation can use changedAttributes properly', () => {
		const scope = {};
		Backbone.Relational.store.addModelScope(scope);

		scope.PetAnimal = Backbone.Relational.Model.extend({
			subModelTypes: {
				cat: 'Cat',
				dog: 'Dog'
			}
		});
		scope.Dog = scope.PetAnimal.extend();
		scope.Cat = scope.PetAnimal.extend();

		scope.PetOwner = Backbone.Relational.Model.extend({
			relations: [
				{
					type: Backbone.Relational.HasMany,
					key: 'pets',
					relatedModel: scope.PetAnimal,
					reverseRelation: {
						key: 'owner'
					}
				}
			]
		});

		const owner = new scope.PetOwner({ id: 'owner-2354' });
		const animal = new scope.Dog({ type: 'dog', id: '238902', color: 'blue' });
		expect(animal.get('color')).toBe('blue');

		let changes = 0;
		let changedAttrs = null;
		animal.on('change', (model) => {
			changes++;
			changedAttrs = model.changedAttributes();
		});

		animal.set({ color: 'green' });
		expect(changes).toBe(1);
		expect(changedAttrs.color).toBe('green');

		owner.set(
			owner.parse({
				id: 'owner-2354',
				pets: [{ id: '238902', type: 'dog', color: 'red' }]
			})
		);

		expect(animal.get('color')).toBe('red');
		expect(changes).toBe(2);
		expect(changedAttrs.color).toBe('red');
	});

	it('change events should not fire on new items in Collection#set', () => {
		let modelChangeEvents = 0;
		let collectionChangeEvents = 0;

		const Animal2 = Animal.extend({
			initialize: function () {
				this.on('all', (name) => {
					if (name.indexOf('change') === 0) {
						modelChangeEvents++;
					}
				});
			}
		});

		const AnimalCollection2 = AnimalCollection.extend({
			model: Animal2,

			initialize: function () {
				this.on('all', (name) => {
					if (name.indexOf('change') === 0) {
						collectionChangeEvents++;
					}
				});
			}
		});

		new Zoo({ id: 'zoo-1' });

		const coll = new AnimalCollection2();
		coll.set([
			{
				id: 'animal-1',
				livesIn: 'zoo-1'
			}
		]);

		expect(collectionChangeEvents).toBe(0);

		modelChangeEvents = collectionChangeEvents = 0;

		coll.at(0).set('name', 'Willie');

		expect(modelChangeEvents).toBe(2);
	});

