	it('Overriding of supermodel relations', () => {
		const models = {};
		Backbone.Relational.store.addModelScope(models);

		models.URL = Backbone.Relational.Model.extend({});

		models.File = Backbone.Relational.Model.extend({
			subModelTypes: {
				video: 'Video',
				publication: 'Publication'
			},

			relations: [
				{
					type: Backbone.Relational.HasOne,
					key: 'url',
					relatedModel: models.URL
				}
			]
		});

		models.Video = models.File.extend({});

		models.Publication = Backbone.Relational.Model.extend({
			relations: [
				{
					type: Backbone.Relational.HasMany,
					key: 'url',
					relatedModel: models.URL
				}
			]
		});

		models.Project = Backbone.Relational.Model.extend({
			relations: [
				{
					type: Backbone.Relational.HasMany,
					key: 'files',
					relatedModel: models.File,
					reverseRelation: {
						key: 'project'
					}
				}
			]
		});

		expect(models.File.prototype.relations.length).toBe(2);
		expect(models.Video.prototype.relations.length).toBe(1);
		expect(models.Publication.prototype.relations.length).toBe(1);

		new models.File();

		expect(models.File.prototype.relations.length).toBe(2);
		expect(models.Video.prototype.relations.length).toBe(2);
		expect(models.Publication.prototype.relations.length).toBe(2);

		const projectDescription = {
			name: 'project1',

			files: [
				{
					name: 'file1 - video subclass',
					type: 'video',
					url: { location: 'http://www.myurl.com/file1.avi' }
				},
				{
					name: 'file2 - file baseclass',
					url: { location: 'http://www.myurl.com/file2.jpg' }
				},
				{
					name: 'file3 - publication',
					type: 'publication',
					url: [
						{ location: 'http://www.myurl.com/file3.pdf' },
						{ location: 'http://www.anotherurl.com/file3.doc' }
					]
				}
			]
		};

		const project = new models.Project(projectDescription);
		const files = project.get('files');
		const file1 = files.at(0);
		const file2 = files.at(1);
		const file3 = files.at(2);

		expect(models.File.prototype.relations.length).toBe(2);
		expect(models.Video.prototype.relations.length).toBe(2);
		expect(models.Publication.prototype.relations.length).toBe(2);

		expect(_.size(file1._relations)).toBe(2);
		expect(_.size(file2._relations)).toBe(2);
		expect(_.size(file3._relations)).toBe(2);

		expect(file1.get('url')).toBeInstanceOf(Backbone.Model);
		expect(file1.getRelation('url')).toBeInstanceOf(Backbone.Relational.HasOne);

		expect(file3.get('url')).toBeInstanceOf(Backbone.Relational.Collection);
		expect(file3.getRelation('url')).toBeInstanceOf(Backbone.Relational.HasMany);
	});

