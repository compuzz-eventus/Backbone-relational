	it('By default, `parse` should only get called on top-level objects; not for nested models and collections', () => {
		const companyData = {
			data: {
				id: 'company-1',
				contacts: [{ id: '1' }, { id: '2' }]
			}
		};

		const Contact = Backbone.Relational.Model.extend();
		const Contacts = Backbone.Relational.Collection.extend({
			model: Contact
		});

		const LocalCompany = Backbone.Relational.Model.extend({
			urlRoot: '/company/',
			relations: [
				{
					type: Backbone.Relational.HasMany,
					key: 'contacts',
					relatedModel: Contact,
					collectionType: Contacts
				}
			]
		});

		let parseCalled = 0;
		LocalCompany.prototype.parse =
			Contact.prototype.parse =
			Contacts.prototype.parse =
				function (resp) {
					parseCalled++;
					return resp.data || resp;
				};

		const company = new LocalCompany(companyData, { parse: true });
		const contacts = company.get('contacts');
		const contact = contacts.first();

		expect(company.id).toBe('company-1');
		expect(contact && contact.id === '1').toBe(true);
		expect(parseCalled).toBe(1);

		company.fetch({
			parse: true,
			response: {
				status: 200,
				responseText: _.clone(companyData)
			}
		});

		expect(parseCalled).toBe(2);

		expect(contacts).toBe(company.get('contacts'));
		expect(contacts.length).toBe(2);
		expect(contact && contact.id === '1').toBe(true);
		expect(contact).toBe(contacts.first());
	});

